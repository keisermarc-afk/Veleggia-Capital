// Extracts the rule calcs from a saved copy of the macro dashboard page into
// reference/dashboard-calcs.js. The parity tests run these exact functions next to
// the app's rules engine. Usage:
//   node tools/extract-reference.mjs <dashboard-index.html> <dashboard version>
import { readFileSync, writeFileSync } from 'node:fs';

const [, , htmlPath, version] = process.argv;
if (!htmlPath) { console.error('usage: node tools/extract-reference.mjs <index.html> <version>'); process.exit(1); }
const html = readFileSync(htmlPath, 'utf8');
const IDS = ['crypto_trend', 'equity_health', 'macro_cycle', 'range_watch', 'setup_watch', 'equity_weekly'];
const blocks = IDS.map(id => {
  const start = html.indexOf(`dash.calc('${id}', {`);
  if (start < 0) throw new Error(`calc ${id} not found`);
  const end = html.indexOf('\n});', start);
  if (end < 0) throw new Error(`end of calc ${id} not found`);
  return html.slice(start, end + 4);
});
const header = `// GENERATED by tools/extract-reference.mjs from the macro dashboard page (files/index.html, version ${version || 'unknown'}).
// Do not edit by hand. These are the dashboard's own rule calcs, kept as the reference the
// app's rules engine (packages/rules) must match. Re-extract whenever a rule changes on the dashboard.
`;
writeFileSync(new URL('../reference/dashboard-calcs.js', import.meta.url), header + blocks.join('\n\n') + '\n');
console.log('extracted', IDS.length, 'calcs');
