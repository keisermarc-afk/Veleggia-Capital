// Writes apps/app/migrations/0002_seed.sql from a fixture folder (the levels and plan in force
// when the app was built), so the app starts with exactly what the dashboard shows.
// Usage: node tools/make-seed.mjs fixtures/2026-11-03
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = process.argv[2];
const parse = (t) => { const L = []; let row = [], cell = '', q = false;
  for (let i = 0; i < t.length; i++) { const ch = t[i];
    if (q) { if (ch === '"') { if (t[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += ch; }
    else if (ch === '"') q = true; else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && t[i + 1] === '\n') i++; row.push(cell); cell = ''; if (row.some(c => c)) L.push(row); row = []; }
    else cell += ch; }
  if (cell || row.length) { row.push(cell); if (row.some(c => c)) L.push(row); }
  const [h, ...b] = L; return b.map(r => Object.fromEntries(h.map((k, j) => [k, r[j] ?? '']))); };
const sq = (v) => "'" + String(v ?? '').replace(/'/g, "''") + "'";
const at = '2026-11-03T00:00:00Z', by = 'seed from dashboard';
const lv = parse(readFileSync(join(dir, 'range_levels.csv'), 'utf8'));
const pl = parse(readFileSync(join(dir, 'weekly_plan.csv'), 'utf8'));
const LC = ['asset','range_high','mid','range_low','set_on','note','proxy_ratio','watch_levels','long_trigger_4h'];
const PC = ['id','week','week_start','week_end','written','section','asset','market','title','trigger','stop','target','risk_class','level','note'];
let sql = `-- GENERATED by tools/make-seed.mjs from ${dir}: the levels and weekly plan in force on the dashboard.\n`;
for (const r of lv) {
  sql += `INSERT INTO range_levels (${LC.join(', ')}, updated_at, updated_by) VALUES (${LC.map(c => sq(r[c])).join(', ')}, ${sq(at)}, ${sq(by)});\n`;
  const d = Object.fromEntries(LC.map(c => [c, r[c]]));
  sql += `INSERT INTO range_levels_history (asset, data, saved_at, saved_by) VALUES (${sq(r.asset)}, ${sq(JSON.stringify(d))}, ${sq(at)}, ${sq(by)});\n`;
}
pl.forEach((r, i) => { sql += `INSERT INTO weekly_plan (pos, ${PC.map(c => c === 'trigger' ? '"trigger"' : c).join(', ')}) VALUES (${i}, ${PC.map(c => sq(r[c])).join(', ')});\n`; });
sql += `INSERT INTO weekly_plan_history (week, data, saved_at, saved_by) VALUES (${sq(pl[0].week + ' (' + pl[0].week_start + ')')}, ${sq(JSON.stringify(pl.map(r => Object.fromEntries(PC.map(c => [c, r[c]])))))}, ${sq(at)}, ${sq(by)});\n`;
writeFileSync('apps/app/migrations/0002_seed.sql', sql);
console.log('seed:', lv.length, 'levels,', pl.length, 'plan rows');
